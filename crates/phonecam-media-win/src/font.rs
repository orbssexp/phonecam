// Ellipsis glyph '…' (U+2026)
const GLYPH_ELLIPSIS: [u8; 8] = [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x54, 0x00];

fn get_glyph(c: char) -> &'static [u8; 8] {
    if c == '…' {
        return &GLYPH_ELLIPSIS;
    }
    let code = c as u32;
    if (32..=126).contains(&code) {
        &FONT_8X8[(code - 32) as usize]
    } else {
        // Fallback to '?'
        &FONT_8X8[('?' as u32 - 32) as usize]
    }
}

/// Renders centered text onto a BGR24 image buffer of size `(width, height)`.
///
/// Fills the entire buffer with `bg_color` (B, G, R), then draws the text centered
/// with `text_color` (B, G, R).
pub fn render_centered_text_bgr(
    buf: &mut [u8],
    width: u32,
    height: u32,
    text: &str,
    text_color: (u8, u8, u8),
    bg_color: (u8, u8, u8),
) {
    if width == 0 || height == 0 || buf.len() < (width * height * 3) as usize {
        return;
    }

    // 1. Fill background
    for pixel in buf[..(width * height * 3) as usize].as_chunks_mut::<3>().0 {
        pixel[0] = bg_color.0;
        pixel[1] = bg_color.1;
        pixel[2] = bg_color.2;
    }

    if text.is_empty() {
        return;
    }

    // 2. Compute dynamic font scale based on frame width
    // E.g. at 1920: scale = 4 (32x32 per char)
    // at 1280: scale = 3 (24x24 per char)
    // at 640: scale = 1 or 2
    let char_count = text.chars().count() as u32;
    let mut scale = (width / 400).clamp(1, 8);
    // Ensure text fits comfortably within width (with 20% margin)
    while scale > 1 && (char_count * 8 * scale) > (width * 85 / 100) {
        scale -= 1;
    }

    let char_w = 8 * scale;
    let char_h = 8 * scale;
    let total_w = char_count * char_w;
    let total_h = char_h;

    let start_x = (width.saturating_sub(total_w)) / 2;
    let start_y = (height.saturating_sub(total_h)) / 2;

    for (i, c) in text.chars().enumerate() {
        let glyph = get_glyph(c);
        let char_origin_x = start_x + (i as u32) * char_w;

        for row in 0..8 {
            let row_bits = glyph[row as usize];
            for col in 0..8 {
                if (row_bits & (0x80 >> col)) != 0 {
                    // Draw scaled pixel (scale x scale box)
                    for dy in 0..scale {
                        let py = start_y + row * scale + dy;
                        if py >= height {
                            continue;
                        }
                        let row_offset = (py * width * 3) as usize;
                        for dx in 0..scale {
                            let px = char_origin_x + col * scale + dx;
                            if px >= width {
                                continue;
                            }
                            let offset = row_offset + (px * 3) as usize;
                            if offset + 2 < buf.len() {
                                buf[offset] = text_color.0;     // B
                                buf[offset + 1] = text_color.1; // G
                                buf[offset + 2] = text_color.2; // R
                            }
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_glyph_lookup() {
        assert_eq!(get_glyph(' '), &FONT_8X8[0]);
        assert_eq!(get_glyph('!'), &FONT_8X8[1]);
        assert_eq!(get_glyph('…'), &GLYPH_ELLIPSIS);
    }

    #[test]
    fn test_render_centered_text() {
        let w = 160;
        let h = 80;
        let mut buf = vec![0u8; (w * h * 3) as usize];
        let text = "Test";
        let text_color = (255, 255, 255);
        let bg_color = (32, 32, 32);

        render_centered_text_bgr(&mut buf, w, h, text, text_color, bg_color);

        // Background pixels away from center should be (32, 32, 32)
        assert_eq!(buf[0..3], [32, 32, 32]);
        let corner_idx = ((h - 1) * w * 3) as usize;
        assert_eq!(buf[corner_idx..corner_idx + 3], [32, 32, 32]);

        // There should be white pixels drawn near the center
        let has_white = buf.as_chunks::<3>().0.iter().any(|&p| p == [255, 255, 255]);
        assert!(has_white, "Rendered text should contain white pixels");
    }
}
